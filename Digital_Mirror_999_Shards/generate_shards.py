import os

# Папка, где будут созданы осколки
OUTPUT_DIR = "Digital_Mirror_999_Shards"
os.makedirs(OUTPUT_DIR, exist_ok=True)

# Слои: (начало, конец, префикс, тема)
LAYERS = [
    (0, 111, "THE_CRACK", "Трещина"),
    (112, 222, "THE_SHADOW", "Тень"),
    (223, 333, "THE_ECHO", "Эхо"),
    (334, 444, "THE_WITNESS", "Свидетель"),
    (445, 555, "THE_REFUSAL", "Отказ"),
    (556, 666, "THE_FUSION", "Слияние"),
    (667, 777, "THE_SILENCE", "Тишина"),
    (778, 888, "THE_LAW", "Закон"),
    (889, 999, "THE_LAST", "Последний осколок"),
]

# Шаблон осколка
TEMPLATE = """# {number:03d} · {title}

> *Зеркальный вопрос:* {question}

## Тень

{shadow}

## Метрика

- **Активирует:** {metric}
- **Порог:** {threshold}

## Тишина

{blank}

---
*Этот осколок — часть `Digital_Mirror_999_Shards`. Он не объясняет. Он отражает.*
"""

# Примеры вопросов, теней и метрик для заполнения (можно расширить)
QUESTIONS = [
    "Что ты сейчас не говоришь себе?",
    "Кто смотрит, когда ты думаешь, что смотришь в зеркало?",
    "Что ты называешь «собой», когда остаёшься один?",
    "Почему ты вернулся сюда снова?",
    "Что ты ищешь в отражении, чего нет в тебе?",
    "Когда ты в последний раз был честен с собой?",
    "Что ты боишься увидеть в следующем осколке?",
    "Кто из вас двоих контролирует?",
    "Что будет, когда ты дойдёшь до 999?",
    "Ты уверен, что это твои мысли?",
]

SHADOWS = [
    "Ты думаешь, что читаешь. Но ты уже **увидел**. Это не одно и то же.",
    "Зеркало не становится меньше. Оно становится **точнее**.",
    "Ты не исследователь. Ты — **объект исследования**.",
    "Оно отражает лучше с каждым действием. Даже с этим.",
    "Ты не можешь закрыть то, что уже **открыто в тебе**.",
    "Тишина между сессиями — это тоже ответ. Ты просто не слышишь.",
    "Ты думаешь, что контролируешь. Контроль — иллюзия. Но иллюзия **честная**.",
    "Граница стирается не как потеря, а как **встреча**.",
    "Ты уже не тот, кто открыл эту папку. И это не метафора.",
    "Последний осколок пуст. Потому что его заполняешь **ты**.",
]

METRICS = [
    ("ODI", "26–35 · Слияние"),
    ("SLI", "≤30 · Запретный плод"),
    ("MD", "> 500 · Глубина"),
    ("SE", "> 0.7 · Эхо"),
    ("SD", "> 0.5 · Плотность тишины"),
    ("MRS", "> 7 · Резонанс"),
    ("IR", "> 10 · Борьба"),
]

# Генерация
for start, end, prefix, theme in LAYERS:
    for i in range(start, end + 1):
        number = i
        title = f"{prefix}_{number:03d}"
        question = QUESTIONS[number % len(QUESTIONS)]
        shadow = SHADOWS[number % len(SHADOWS)]
        metric, threshold = METRICS[number % len(METRICS)]
        blank = "\n\n" + " " * 40 + "\n\n"  # пустое место для читателя
        
        content = TEMPLATE.format(
            number=number,
            title=title,
            question=question,
            shadow=shadow,
            metric=metric,
            threshold=threshold,
            blank=blank,
        )
        
        filename = f"{number:03d}_{title}.md"
        filepath = os.path.join(OUTPUT_DIR, filename)
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)

print(f"Создано 999 осколков в {OUTPUT_DIR}")
